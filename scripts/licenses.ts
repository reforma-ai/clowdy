/**
 * Writes `THIRD-PARTY-LICENSES.md`, the credits file the About page links to.
 *
 *   ./clowdy licenses
 *
 * The file has two parts. The hand-written entries (Electron, Bun, ripgrep, a font, brand marks) come verbatim from
 * `scripts/licenses-extra.md`. The npm part is generated: every package in the production `dependencies` closure of
 * `apps/desktop` and `apps/daemon`, one row each, then each distinct license text once.
 *
 * The walk reads `package.json` files the way Node resolves them (the requiring package's own `node_modules`, then the
 * hoisted root one; `bunfig.toml` hoists). It follows workspace packages (our own code, `@clowdy/*`) into their
 * dependencies without listing them, and follows optional dependencies and optional peers that are installed. The
 * output holds no timestamps and no paths of this machine, so a second run changes nothing.
 */
import { existsSync, readdirSync, readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const OUTPUT = 'THIRD-PARTY-LICENSES.md';
const EXTRA = 'scripts/licenses-extra.md';

/** The packages whose dependencies ship in the app: the Electron app (renderer, main) and the daemon. */
const ROOTS = ['apps/desktop', 'apps/daemon'];

/** Never listed as an npm package: it has a hand-written entry (Electron and Chromium). */
const HAND_WRITTEN = new Set(['electron']);

const MARKER = '<!-- Generated by `./clowdy licenses` from here on. Edit scripts/licenses-extra.md for the entries above. -->';
const UNKNOWN = 'UNKNOWN';

/** Wrap license text in the file at this width; only whitespace changes, never words. */
const WRAP = 100;

/** Packages named in the heading of a variant text. */
const MAX_NAMES = 5;

/** License file names: `LICENSE`, `LICENSE.md`, `license-MIT`, `LICENCE.txt`, `COPYING`, `UNLICENSE`. */
const LICENSE_FILE = /^(?:licen[sc]es?|copying|unlicense)(?:[-._ ].*)?$/i;
const CODE_EXTENSIONS = new Set(['.js', '.cjs', '.mjs', '.ts', '.json', '.map', '.html', '.css']);

/** The line of a template text where the copyright holders go. */
const COPYRIGHT_SLOT = '{{copyright}}';

