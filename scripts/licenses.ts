/** A license title (`MIT License`, `(The MIT license)`) in front of the grant: the same text with another title is one text. */
const TITLE = /^(?:#+\s*)?\(?(?:the\s+)?(?:mit|isc|bsd(?:[- ][23][- ]clause)?)(?:\s+licen[sc]e)?\)?(?:\s*\(mit\))?\s+(?=Permission|Redistribution)/i;

/** Stands where the copyright lines of a license text were taken out: they are in the table, per package. */
const COPYRIGHT_PLACEHOLDER = '[The copyright notice of each package is in the table above]';

interface PackageJson {
    name?: string
    version?: string
    license?: unknown
    licenses?: unknown
    author?: unknown
    repository?: unknown
    homepage?: unknown
    dependencies?: Record<string, string>
    optionalDependencies?: Record<string, string>
    peerDependenciesMeta?: Record<string, unknown>
}

interface Row {
    name: string
    version: string
    license: string
    /** The notice lines of the package's license files, or the author when they hold none. */
    copyright: string[]
    /** True when the copyright part is not from a license file. */
    fallback: boolean
    url: string
    /** Texts this package's license is made of: its license files, or the SPDX template. */
    texts: string[]
}

export async function licensesCommand(repoRoot: string, args: string[]): Promise<void> {
    if (args.length > 0) {
        die('Usage: ./clowdy licenses');
    }

    const warnings: string[] = [];
    const rows = collectRows(repoRoot, warnings);
    const extra = readFileSync(path.join(repoRoot, EXTRA), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    const texts = collectTexts(rows);
    const output = [extra, MARKER, renderPackages(rows), renderTexts(texts)].join('\n\n') + '\n';

    writeFileSync(path.join(repoRoot, OUTPUT), output);

    for (const warning of warnings) {
        console.error(`Warning: ${ warning }`);
    }

    const histogram = new Map<string, number>();

    for (const row of rows) {
        histogram.set(row.license, (histogram.get(row.license) ?? 0) + 1);
    }

    console.log(`Wrote ${ OUTPUT }: ${ rows.length } packages, ${ texts.length } license texts`);

    for (const [license, count] of [...histogram].sort((a, b) => b[1] - a[1] || compare(a[0], b[0]))) {
        console.log(`  ${ license }: ${ count }`);
    }
}

/** One row per distinct name@version of the production closure, sorted by name and version. */
function collectRows(repoRoot: string, warnings: string[]): Row[] {
    const packages = new Map<string, { dir: string, json: PackageJson }>();
    const visited = new Set<string>();

    function walk(dir: string): void {
        if (visited.has(dir)) {
            return;
        }

        visited.add(dir);

        const json = readJson(path.join(dir, 'package.json'));

        if (json.name && HAND_WRITTEN.has(json.name)) {
            return;
        }

        // Workspace packages are our own code: not listed, but what they depend on ships.
        const own = !path.relative(repoRoot, dir).split(path.sep).includes('node_modules');

        if (!own && json.name) {
            const key = `${ json.name }@${ json.version }`;

            if (!packages.has(key)) {
                packages.set(key, { dir, json });
            }
        }

        // A bundler also picks up an installed optional dependency, and an optional peer that is installed (`debug` loads
        // `supports-color` when it is there). A required peer is the host's own dependency, so it is not followed, and
        // type declarations never ship. A missing optional one is no error; a missing `dependencies` entry is.
        const optional = [
            ...Object.keys(json.optionalDependencies ?? {}),
            ...Object.keys(json.peerDependenciesMeta ?? {}).filter(name => !name.startsWith('@types/')),
        ];

        for (const name of new Set([...Object.keys(json.dependencies ?? {}), ...optional])) {
            const found = resolvePackage(name, dir);

            if (found) {
                walk(found);
            }
            else if (!optional.includes(name)) {
                warnings.push(`${ name }, a dependency of ${ json.name }, is not installed`);
            }
        }
    }

    for (const root of ROOTS) {
        const dir = path.join(repoRoot, root);

        if (!existsSync(path.join(dir, 'package.json'))) {
            die(`${ root } has no package.json: the list of shipped packages would be incomplete`);
        }

        walk(dir);
    }

    const rows: Row[] = [];

    for (const { dir, json } of packages.values()) {
        rows.push(buildRow(dir, json, warnings));
    }

    return rows.sort((a, b) => compare(a.name, b.name) || a.version.localeCompare(b.version, 'en', { numeric: true }));
}

/** Node's lookup: the `node_modules` of the requiring package and of each parent folder. */
function resolvePackage(name: string, from: string): string | undefined {
    for (let dir = from; ; dir = path.dirname(dir)) {
        const candidate = path.join(dir, 'node_modules', name);

        if (existsSync(path.join(candidate, 'package.json'))) {
            return realpathSync(candidate);
        }

        if (path.dirname(dir) === dir) {
            return undefined;
        }
    }
}

function buildRow(dir: string, json: PackageJson, warnings: string[]): Row {
    const name = json.name ?? '';
    const version = json.version ?? '';
    const license = declaredLicense(json);
    const texts = licenseFiles(dir).map(file => readFileSync(path.join(dir, file), 'utf8').replace(/\r\n?/g, '\n'));
    const url = sourceUrl(json) ?? `https://www.npmjs.com/package/${ name }`;
    const notices = [...new Set(texts.flatMap(text => findNotice(text.split('\n'))?.lines ?? []))];
    const fallback = notices.length === 0;

    if (license === UNKNOWN) {
        warnings.push(`${ name }@${ version } declares no license`);
    }

    if (texts.length === 0) {
        texts.push(TEMPLATES[license] ?? noTemplateText(license));

        if (!TEMPLATES[license]) {
            warnings.push(`${ name }@${ version } ships no license file and ${ license } has no template here`);
        }
    }

    return {
        name,
        version,
        license,
        copyright: fallback ? [authorCopyright(json)] : notices,
        fallback,
        url,
        texts,
    };
}

/** For a license without a template: say so, and point to the SPDX page when the id names one license. */
function noTemplateText(license: string): string {
    if (license === UNKNOWN) {
        return 'This package declares no license and ships no license file.';
    }

    const page = /^[\w.+-]+$/.test(license) ? `https://spdx.org/licenses/${ license }.html` : 'https://spdx.org/licenses/';

    return `This package ships no license file. The text of ${ license } is at ${ page }`;
}

/** The SPDX expression from `license`, or from the old `licenses` array. Both may hold strings or `{ type }` objects. */
function declaredLicense(json: PackageJson): string {
    const license = licenseType(json.license);

    if (license) {
        return license;
    }

    const list = Array.isArray(json.licenses) ? json.licenses : json.licenses ? [json.licenses] : [];
    const types = list.map(licenseType).filter((type): type is string => type !== undefined);

    // The old array lists alternatives.
    return types.length === 0 ? UNKNOWN : types.length > 1 ? `(${ types.join(' OR ') })` : types[0]!;
}

function licenseType(entry: unknown): string | undefined {
    const type = typeof entry === 'string' ? entry : (entry as { type?: unknown } | null | undefined)?.type;

    return typeof type === 'string' && type.trim() !== '' ? type.trim() : undefined;
}

function licenseFiles(dir: string): string[] {
    return readdirSync(dir)
        .filter(file => LICENSE_FILE.test(file) && !CODE_EXTENSIONS.has(path.extname(file).toLowerCase()) && statSync(path.join(dir, file)).isFile())
        .sort(compare);
}

/**
 * A line that states a copyright holder: it starts with `Copyright`, `(c)` or a copyright sign, or has a short lead-in
 * (`Original code Copyright Julian Gruber`). A heading, a sentence about "copyright notice" and a template placeholder
 * (`<year>`, `[yyyy]`) do not count.
 */
function isCopyrightLine(line: string): boolean {
    const text = line.trim();

    return /^(?:(?:[A-Za-z][\w-]*\s+){0,3}Copyright\s+(?:\([cC]\)\s*)?[\dA-Za-z©]|\([cC]\)\s*\d|©)/.test(text)
        && !/\bCopyright\s+(?:notice|owner|holder|statement|law|license|and|in|is|on|to|of|for|that|or|the)\b/i.test(text)
        && !/[<[{](?:year|yyyy|name of|copyright|owner|fullname|your)/i.test(text)
        && !/\bCopyright\s+(?:\([cC]\)\s*)?(?:yyyy|year)\b/i.test(text);
}

/** `Copyright (c) <author>` from `package.json`, for a package whose files carry no copyright line. */
function authorCopyright(json: PackageJson): string {
    const author = json.author;
    const raw = typeof author === 'string' ? author : (author as { name?: unknown } | undefined)?.name;
    const name = typeof raw === 'string' ? raw.replace(/<[^>]*>|\([^)]*\)/g, '').trim() : '';

    return `Copyright (c) ${ name || `the ${ json.name } authors` }`;
}

/** The repository as a browsable `https://` address, else the homepage. */
function sourceUrl(json: PackageJson): string | undefined {
    const repository = json.repository;
    const raw = typeof repository === 'string' ? repository : (repository as { url?: unknown } | undefined)?.url;
    const fromRepository = typeof raw === 'string' ? browsable(raw.trim()) : undefined;

    return fromRepository ?? (typeof json.homepage === 'string' && json.homepage.trim() ? json.homepage.trim() : undefined);
}

function browsable(repository: string): string | undefined {
    const shorthand = /^(?:github:)?([\w.-]+\/[\w.-]+)$/.exec(repository);

    if (shorthand) {
        return `https://github.com/${ shorthand[1] }`;
    }

    const host = /^(gitlab|bitbucket):([\w.-]+\/[\w.-]+)$/.exec(repository);

    if (host) {
        return `https://${ host[1] }.${ host[1] === 'gitlab' ? 'com' : 'org' }/${ host[2] }`;
    }

    const url = repository
        .replace(/^git\+/, '')
        .replace(/^(?:git|ssh):\/\/(?:git@)?/, 'https://')
        .replace(/^git@([^:]+):/, 'https://$1/')
        .replace(/\.git(?=#|$)/, '')
        .replace(/#.*$/, '');

    return /^https?:\/\//.test(url) ? url : undefined;
}

// MARK: Texts

interface LicenseText {
    /** The most used declared license among the packages whose text this is. */
    id: string
    body: string
    /** Names of the packages that carry this text, sorted. */
    packages: string[]
}

/** The distinct license texts, each once: equal once copyright lines, a title, whitespace and quote style are ignored. */
function collectTexts(rows: Row[]): LicenseText[] {
    const byKey = new Map<string, { body: string, ids: Map<string, number>, packages: Set<string> }>();

    for (const row of rows) {
        for (const text of row.texts) {
            const key = textKey(text);
            const entry = byKey.get(key) ?? { body: displayText(text), ids: new Map(), packages: new Set() };

            entry.ids.set(row.license, (entry.ids.get(row.license) ?? 0) + 1);
            entry.packages.add(row.name);
            byKey.set(key, entry);
        }
    }

    return [...byKey.entries()]
        .map(([key, { body, ids, packages }]) => ({
            key,
            id: [...ids].sort((a, b) => b[1] - a[1] || compare(a[0], b[0]))[0]![0],
            body,
            packages: [...packages].sort(compare),
        }))
        .sort((a, b) => compare(a.id, b.id) || b.packages.length - a.packages.length || compare(a.key, b.key))
        .map(({ id, body, packages }) => ({ id, body, packages }));
}

function textKey(text: string): string {
    return withoutNotice(text, '')
        .replace(/[\u2018\u2019\u201c\u201d']/g, '"')
        .replace(/\s+/g, ' ')
        .trim()
        .replace(TITLE, '')
        .replace(/\.$/, '');
}

/** A copyright line, or the line of a template where the holders go. */
function isNotice(line: string): boolean {
    return line.includes(COPYRIGHT_SLOT) || isCopyrightLine(line);
}

function isRightsLine(line: string): boolean {
    return /^all rights reserved\.?$/i.test(line.trim());
}

/** The first run of copyright lines in a license text: where it sits, and the lines it holds. */
interface Notice {
    /** Index of its first line and of its last line in the text's lines. */
    start: number
    end: number
    /** Its non-blank lines, trimmed. */
    lines: string[]
}

/**
 * The first run of copyright lines: blank lines, `All rights reserved.` and the second line of a holder that wraps
 * (the first one ends with a comma) between them included. Later copyright lines are part of the text, as in a license
 * that credits several works, and stay there.
 */
function findNotice(lines: string[]): Notice | undefined {
    const start = lines.findIndex(isNotice);

    if (start === -1) {
        return undefined;
    }

    let end = start;

    for (let index = start + 1; index < lines.length; index += 1) {
        const line = lines[index]!;
        const wraps = index === end + 1 && lines[end]!.trimEnd().endsWith(',') && line.trim() !== '';

        if (isNotice(line) || wraps) {
            end = index;
        }
        else if (line.trim() !== '' && !isRightsLine(line)) {
            break;
        }
    }

    // `end` is the last copyright line of the run; a rights line right after it belongs to the notice.
    while (isRightsLine(lines[end + 1] ?? '')) {
        end += 1;
    }

    return {
        start,
        end,
        lines: lines.slice(start, end + 1).map(line => line.trim()).filter(line => line !== ''),
    };
}

/** The text with its notice taken out, `replacement` standing there. Every line it took out is in a package's row. */
function withoutNotice(text: string, replacement: string): string {
    const lines = text.split('\n');
    const notice = findNotice(lines);

    return notice ? [...lines.slice(0, notice.start), replacement, ...lines.slice(notice.end + 1)].join('\n') : text;
}

/** The text with its notice replaced by one placeholder line, wrapped and with single blank lines. */
function displayText(text: string): string {
    return withoutNotice(text, COPYRIGHT_PLACEHOLDER)
        .split('\n')
        .flatMap(line => wrap(line.trimEnd()))
        .join('\n')
        .replace(/\n{3,}/g, '\n\n')
        .trim();
}

/** Breaks a long line at spaces, keeping its indent. A word is never split. */
function wrap(line: string): string[] {
    if (line.length <= WRAP) {
        return [line];
    }

    const indent = /^\s*/.exec(line)![0];
    const out: string[] = [];
    let current = indent;

    for (const word of line.trim().split(/\s+/)) {
        if (current.trim() !== '' && current.length + 1 + word.length > WRAP) {
            out.push(current);
            current = indent;
        }

        current += (current.trim() === '' ? '' : ' ') + word;
    }

    out.push(current);

    return out;
}

// MARK: Rendering

function renderPackages(rows: Row[]): string {
    const lines = [
        '## npm packages',
        '',
        `${ rows.length } packages from the production dependencies of the desktop app and the daemon, with the license each declares in its \`package.json\`. The copyright column is the notice from the package's own license file, line by line.`,
        '',
        '| Package | Version | License | Copyright | Source |',
        '| --- | --- | --- | --- | --- |',
    ];

    for (const row of rows) {
        const copyright = row.copyright.map(line => escapeCell(line)).join('<br>') + (row.fallback ? ' †' : '');

        lines.push(`| \`${ row.name }\` | ${ row.version } | ${ escapeCell(row.license) } | ${ copyright } | ${ row.url } |`);
    }

    lines.push('', '† The license file of the package has no copyright line, or the package ships no license file. The holder named here is its `author` in `package.json`, or its authors when it names none. Without a license file, the text is the standard text of the license the package declares.');

    return lines.join('\n');
}

function renderTexts(texts: LicenseText[]): string {
    const lines = [
        '## License texts',
        '',
        'Each distinct text once. The copyright notices that go with it are the lines of the packages above. A license with more than one text names the packages of each text after the first.',
    ];
    const listed = new Set<string>();

    for (const { id, body, packages } of texts) {
        // Sorted by license, then by how many packages share the text: the first of a license is its common text.
        const first = !listed.has(id);

        listed.add(id);
        const fence = body.includes('```') ? '````' : '```';

        lines.push('', `### ${ first ? id : `${ id } (${ nameList(packages) })` }`, '', `${ fence }text`, body, fence);
    }

    return lines.join('\n');
}

function nameList(names: string[]): string {
    return names.length > MAX_NAMES ? `${ names.length } packages` : names.join(', ');
}

/** Table cell text: a pipe would end the cell, and a `<` or `*` would start markup. */
function escapeCell(text: string): string {
    return text.replace(/[\\|*_<>[\]`]/g, char => `\\${ char }`);
}

// MARK: Helpers

/** A malformed `package.json` fails the run: a package skipped here would be missing from a legal file. */
function readJson(file: string): PackageJson {
    try {
        return JSON.parse(readFileSync(file, 'utf8')) as PackageJson;
    }
    catch (error) {
        throw new Error(`${ file }: ${ error instanceof Error ? error.message : String(error) }`, { cause: error });
    }
}

/** Plain code point order: the same on every machine, unlike a locale's. */
function compare(a: string, b: string): number {
    return a < b ? -1 : a > b ? 1 : 0;
}

function die(message: string): never {
    console.error(message);
    process.exit(1);
}
